"""Regenerate the site subset and same-typeface fallback from official OFL TTFs.

Requires fonttools[woff]. Usage:
  python3 scripts/generate-shonan-japanese-fonts.py --source-dir /path/to/official/ttfs
"""

import argparse
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


def unicode_ranges(codepoints):
    ranges = []
    ordered = sorted(codepoints)
    start = end = ordered[0]
    for codepoint in ordered[1:]:
        if codepoint == end + 1:
            end = codepoint
            continue
        ranges.append(f"U+{start:X}-{end:X}" if start != end else f"U+{start:X}")
        start = end = codepoint
    ranges.append(f"U+{start:X}-{end:X}" if start != end else f"U+{start:X}")
    return ", ".join(ranges)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    target = root / "public/fonts/shonan-reference"
    codepoints = set(range(32, 127)) | {0xA0, 0x3000}
    for directory in [root / "app", root / "shared", root / "public/illustrations"]:
        for path in directory.rglob("*"):
            if path.suffix in {".ts", ".tsx", ".json", ".svg"}:
                codepoints.update(ord(char) for char in path.read_text())

    results = []
    fallback_faces = ["/* Generated by scripts/generate-shonan-japanese-fonts.py. */\n"]
    for weight, numeric_weight in [("Regular", 400), ("Medium", 500), ("Bold", 700), ("Black", 900)]:
        source = args.source_dir / f"ZenKakuGothicNew-{weight}.ttf"
        font = TTFont(source, recalcTimestamp=False)
        complete_cmap = set(font.getBestCmap())
        font.flavor = "woff2"
        font.save(target / f"ZenKakuGothicNew-{weight}-Full.woff2")

        options = subset.Options()
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codepoints)
        subsetter.subset(font)
        output = target / f"ZenKakuGothicNew-{weight}.woff2"
        font.save(output)
        # Exclude the subset's codepoints so swap rendering never requests the
        # complete file merely while the initial subset is still downloading.
        fallback_range = unicode_ranges(complete_cmap - set(font.getBestCmap()))
        fallback_faces.append(
            "@font-face {\n"
            "  font-family: 'YottaByte Zen Full';\n"
            f"  src: url('/fonts/shonan-reference/ZenKakuGothicNew-{weight}-Full.woff2') format('woff2');\n"
            "  font-style: normal;\n"
            f"  font-weight: {numeric_weight};\n"
            "  font-display: swap;\n"
            f"  unicode-range: {fallback_range};\n"
            "}\n"
        )
        results.append(
            {
                "font": weight,
                "subset_characters": len(font.getBestCmap()),
                "subset_bytes": output.stat().st_size,
            }
        )
    (root / "app/_components/shonan/fontFallback.css").write_text("\n".join(fallback_faces))
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
